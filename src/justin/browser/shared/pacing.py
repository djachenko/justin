"""Паузы между действиями в браузере.

Числа эмпирические: пришли из первой версии визарда и подбирались на глаз,
измерений за ними нет. Каждая пауза варьируется множителем, поэтому одинаковые
по смыслу задержки всё равно получаются разной длины — прогон не выглядит
метрономом.
"""
import math
import random
import time

PACE = 1.0  # общий множитель: 0 — без задержек, 1 — норма, 2 — вдвое медленнее

SPREAD = 2.0  # во сколько раз пауза может отличаться от заданной в обе стороны

BETWEEN_FIELDS = 0.3  # соседние поля одной формы
AFTER_SCROLL = 0.3  # прокрутка до элемента, странице надо доехать
AFTER_ACTION = 0.5  # клик или ввод, на который страница отвечает перерисовкой
PAGE_SETTLE = 2.0  # переход между страницами и шагами визарда


def varied(seconds: float, spread: float = SPREAD) -> float:
    """От seconds / spread до seconds * spread.

    Множителем, а не слагаемым: замедлиться вдвое и ускориться вдвое — отклонения
    одного размера, и выпадать они должны одинаково часто. Отсюда равномерность
    по логарифму: при сложении диапазон выше единицы вышел бы шире, чем ниже.
    """
    if spread <= 1:
        return seconds

    limit = math.log(spread)

    return seconds * math.exp(random.uniform(-limit, limit))


def pause(seconds: float, spread: float = SPREAD) -> None:
    if PACE <= 0:
        return

    time.sleep(PACE * varied(seconds, spread))
