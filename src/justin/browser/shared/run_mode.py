"""Режим запуска: из-под отладчика IDE или в проде.

Разница в двух вещах — показывать ли окно браузера и вываливать ли дамп страницы,
когда ожидание не дождалось. И то и другое нужно человеку у клавиатуры и мешает
в обычном прогоне.
"""
import sys


def is_debug() -> bool:
    """Отладчик ставит трассировщик, а PyCharm вдобавок подгружает pydevd."""
    return sys.gettrace() is not None or "pydevd" in sys.modules
